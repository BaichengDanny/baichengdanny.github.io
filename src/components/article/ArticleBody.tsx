import { isValidElement, type ComponentPropsWithoutRef, type ReactElement, type ReactNode } from 'react';
import ReactMarkdown, { type Components } from 'react-markdown';
import remarkGfm from 'remark-gfm';
import remarkMath from 'remark-math';
import rehypeKatex from 'rehype-katex';
import rehypeSlug from 'rehype-slug';
import { CornerUpLeft } from 'lucide-react';
import CodeBlock from './CodeBlock';
import { REFERENCES_LABEL } from '../../lib/footnotes';
import type { BibEntry } from '../../lib/bibtex';
import remarkCitations from '../../lib/remarkCitations';

type HeadingTag = 'h1' | 'h2' | 'h3' | 'h4';

const headingClasses: Record<HeadingTag, string> = {
  h1: 'text-xl md:text-2xl lg:text-3xl mt-8 md:mt-10 mb-4 md:mb-6',
  h2: 'text-lg md:text-xl lg:text-2xl mt-6 md:mt-8 mb-3 md:mb-4',
  h3: 'text-base md:text-lg lg:text-xl mt-4 md:mt-6 mb-2 md:mb-3',
  h4: 'text-base md:text-lg mt-4 mb-2',
};

function createHeading(Tag: HeadingTag) {
  return function Heading({ id, children }: ComponentPropsWithoutRef<HeadingTag>) {
    return (
      <Tag id={id} className={`group scroll-mt-4 font-bold serif dark:text-gray-100 break-words ${headingClasses[Tag]}`}>
        {children}
        {id && (
          <a
            href={`#${id}`}
            aria-label="Link to this section"
            className="ml-2 font-normal no-underline text-gray-300 opacity-0 transition-opacity group-hover:opacity-100 focus:opacity-100 hover:text-red-600 dark:text-gray-600 dark:hover:text-red-400"
          >
            #
          </a>
        )}
      </Tag>
    );
  };
}

function isExternal(href?: string) {
  return !!href && /^https?:\/\//.test(href);
}

const components: Components = {
  h1: createHeading('h1'),
  h2: createHeading('h2'),
  h3: createHeading('h3'),
  h4: createHeading('h4'),
  p: ({ children }) => (
    <p className="text-sm md:text-base lg:text-lg leading-relaxed mb-3 md:mb-4 dark:text-gray-300 break-words">{children}</p>
  ),
  // Footnote refs/backrefs rely on the id and aria props generated by remark-gfm.
  a: ({ node, href, children, className, ...rest }) => {
    const properties = node?.properties ?? {};

    if ('dataFootnoteRef' in properties) {
      return (
        <a href={href} {...rest} className="footnote-ref no-underline text-red-600 hover:text-red-800 dark:text-red-400 dark:hover:text-red-300">
          [{children}]
        </a>
      );
    }

    if ('dataFootnoteBackref' in properties) {
      return (
        <a href={href} {...rest} className="inline-flex align-middle text-gray-400 hover:text-red-600 dark:hover:text-red-400">
          <CornerUpLeft aria-hidden="true" className="h-3.5 w-3.5" />
        </a>
      );
    }

    return (
      <a
        href={href}
        {...rest}
        className="text-red-600 hover:text-red-800 dark:text-red-400 dark:hover:text-red-300 break-words"
        {...(isExternal(href) ? { target: '_blank', rel: 'noopener noreferrer' } : {})}
      >
        {children}
      </a>
    );
  },
  section: ({ node, children, className, ...rest }) =>
    node?.properties && 'dataFootnotes' in node.properties ? (
      <section {...rest} className="footnotes mt-12 pt-2 border-t border-gray-200 dark:border-gray-700">
        {children}
      </section>
    ) : (
      <section {...rest} className={className}>{children}</section>
    ),
  ul: ({ children }) => <ul className="list-disc pl-6 mb-3 md:mb-4 space-y-1 md:space-y-2 dark:text-gray-300">{children}</ul>,
  ol: ({ children }) => <ol className="list-decimal pl-6 mb-3 md:mb-4 space-y-1 md:space-y-2 dark:text-gray-300">{children}</ol>,
  li: ({ id, children }) => (
    <li id={id} className="text-sm md:text-base lg:text-lg leading-relaxed dark:text-gray-300 break-words">{children}</li>
  ),
  blockquote: ({ children }) => (
    <blockquote className="border-l-4 border-gray-300 dark:border-gray-600 pl-3 md:pl-4 italic my-3 md:my-4 dark:text-gray-300 text-sm md:text-base break-words">
      {children}
    </blockquote>
  ),
  img: ({ src, alt }) => (
    <img src={typeof src === 'string' ? src : undefined} alt={alt ?? ''} loading="lazy" className="mx-auto rounded-md" />
  ),
  table: ({ children }) => (
    <div className="overflow-x-auto my-4">
      <table className="my-0">{children}</table>
    </div>
  ),
  pre: ({ children }) => {
    const codeElement = (Array.isArray(children) ? children[0] : children) as ReactNode;
    if (!isValidElement(codeElement)) return <pre>{children}</pre>;

    const { className, children: code } = (codeElement as ReactElement<{ className?: string; children?: ReactNode }>).props;
    const language = /language-([\w+#-]+)/.exec(className || '')?.[1];
    return <CodeBlock code={String(code ?? '').replace(/\n$/, '')} language={language} />;
  },
  code: ({ children }) => (
    <code className="bg-gray-100 dark:bg-gray-800 px-1 py-0.5 rounded font-mono text-[0.85em] dark:text-gray-200 break-words">
      {children}
    </code>
  ),
};

interface ArticleBodyProps {
  content: string;
  bibliography?: Record<string, BibEntry>;
}

export default function ArticleBody({ content, bibliography = {} }: ArticleBodyProps) {
  return (
    <ReactMarkdown
      remarkPlugins={[remarkGfm, remarkMath, [remarkCitations, { entries: bibliography }]]}
      remarkRehypeOptions={{
        footnoteLabel: REFERENCES_LABEL,
        footnoteLabelProperties: { className: [] },
        footnoteBackLabel: (index) => `Back to citation ${index + 1}`,
      }}
      rehypePlugins={[rehypeSlug, [rehypeKatex, { strict: false }]]}
      components={components}
    >
      {content}
    </ReactMarkdown>
  );
}
